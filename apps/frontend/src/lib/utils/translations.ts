/**
 * Convert flat translation map (e.g. { 'header.menu.home': 'Главная' }) to nested object
 * so it matches the shape expected by useTranslation (e.g. { header: { menu: { home: 'Главная' } } }).
 */
export function flatToNested(flat: Record<string, string>): Record<string, unknown> {
  const result: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(flat)) {
    if (!key || value === undefined) continue;
    const keys = key.split('.');
    let current: Record<string, unknown> = result;
    for (let i = 0; i < keys.length - 1; i++) {
      const k = keys[i];
      if (!current[k] || typeof current[k] !== 'object') {
        current[k] = {};
      }
      current = current[k] as Record<string, unknown>;
    }
    current[keys[keys.length - 1]] = value;
  }
  return result;
}

/**
 * Flatten translationKeys object to get all keys
 * Returns an array of all translation key strings
 */
export function getAllTranslationKeys(): string[] {
  const keys: string[] = [];
  
  function traverse(obj: any, prefix = '') {
    for (const key in obj) {
      const value = obj[key];
      const fullKey = prefix ? `${prefix}.${key}` : key;
      
      if (typeof value === 'string') {
        // This is a translation key string
        keys.push(value);
      } else if (typeof value === 'object' && value !== null) {
        // Continue traversing
        traverse(value, fullKey);
      }
    }
  }
  
  traverse(translationKeys);
  return [...new Set(keys)].sort(); // Remove duplicates and sort
}

